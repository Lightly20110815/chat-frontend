export type TranslationKey = keyof typeof EN_MESSAGES
export type TranslationParams = Record<string, string | number | null | undefined>

const MESSAGES: Record<SupportedLocale, Record<TranslationKey, string>> = {
  en: EN_MESSAGES,
  'zh-CN': ZH_CN_MESSAGES,
}

export function detectSystemLocale(): SupportedLocale {
  const languages = typeof navigator !== 'undefined'
    ? [...(navigator.languages ?? []), navigator.language].filter(Boolean)
    : []

  const primary = languages.find((language) => language.toLowerCase().startsWith('zh'))

  return primary ? 'zh-CN' : 'en'
}

export function resolveLocale(mode: LocaleMode): SupportedLocale {
  return mode === 'system' ? detectSystemLocale() : mode
}

export function translate(
  locale: SupportedLocale,
  key: TranslationKey,
  params?: TranslationParams,
): string {
  const template = MESSAGES[locale][key] ?? EN_MESSAGES[key]

  if (!params) {
    return template
  }

  return template.replace(/\{(\w+)\}/g, (_, token: string) => {
    const value = params[token]
    return value === undefined || value === null ? '' : String(value)
  })
}

